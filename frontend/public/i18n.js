// One-time migration of settings saved under the project's previous key prefix
try {
  Object.keys(localStorage).filter(k => k.startsWith('hitster:')).forEach(k => {
    const key = 'songline:' + k.slice(8);
    if (localStorage.getItem(key) === null) localStorage.setItem(key, localStorage.getItem(k));
    localStorage.removeItem(k);
  });
} catch (e) {}

const LANGS = ['de', 'en'];
let lang = (() => {
  try {
    const saved = localStorage.getItem('songline:lang');
    if (LANGS.includes(saved)) return saved;
  } catch (e) {}
  return (navigator.language || 'de').toLowerCase().startsWith('de') ? 'de' : 'en';
})();

// Translate a key; {placeholders} are filled from params
function L(key, params = {}) {
  const text = I18N[lang][key] ?? I18N.de[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, p) => (params[p] ?? m));
}

// Team names come from the server in German ("Team Lila") – show them in the player's language
const TEAM_NAMES = { 'Team Lila': 'team-0', 'Team Pink': 'team-1', 'Team Blau': 'team-2', 'Team Grün': 'team-3' };
function un(name) {
  return TEAM_NAMES[name] ? L('team.' + TEAM_NAMES[name]) : name;
}

// Server messages: { key, params } (fallback: German text in message)
function serverText({ key, params, message } = {}) {
  if (key && (I18N[lang][key] || I18N.de[key])) {
    const p = { ...params };
    if (p.name) p.name = un(p.name);
    return L(key, p);
  }
  return message || '';
}

// Apply translations to all elements with data-i18n* attributes
function applyI18n(root = document) {
  document.documentElement.lang = lang;
  document.title = L('doc.title');
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = L(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = L(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = L(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = L(el.dataset.i18nTitle); el.setAttribute('aria-label', el.title); });
  root.querySelectorAll('[data-i18n-alt]').forEach(el => { el.alt = L(el.dataset.i18nAlt); });
  root.querySelectorAll('[data-i18n-n]').forEach(el => { el.textContent = L(el.dataset.i18nN, { n: el.value }); });
  document.querySelectorAll('.lang-btn').forEach(b => b.classList.toggle('active', b.dataset.lang === lang));
}

const langListeners = [];
function onLangChange(fn) { langListeners.push(fn); }

function setLang(next) {
  if (!LANGS.includes(next) || next === lang) return;
  lang = next;
  try { localStorage.setItem('songline:lang', lang); } catch (e) {}
  applyI18n();
  langListeners.forEach(fn => { try { fn(); } catch (e) { console.error(e); } });
}

window.addEventListener('DOMContentLoaded', () => applyI18n());
